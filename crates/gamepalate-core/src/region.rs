use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct Region([u8; 2]);

impl Region {
    pub const ITALY: Region = Region(*b"IT");

    pub fn new(code: &str) -> Option<Region> {
        match code.as_bytes() {
            &[first, second] if first.is_ascii_uppercase() && second.is_ascii_uppercase() => {
                Some(Region([first, second]))
            }
            _ => None,
        }
    }

    pub fn as_str(&self) -> &str {
        std::str::from_utf8(&self.0).expect("a region is two ASCII letters")
    }

    pub fn country_name(&self) -> Option<&'static str> {
        COUNTRIES
            .iter()
            .find(|(code, _)| *code == self.as_str())
            .map(|(_, name)| *name)
    }
}

pub fn countries() -> impl Iterator<Item = (Region, &'static str)> {
    COUNTRIES
        .iter()
        .filter_map(|(code, name)| Region::new(code).map(|region| (region, *name)))
}

